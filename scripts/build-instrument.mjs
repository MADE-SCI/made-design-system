import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('src/instrument.tokens.json', root), 'utf8'));
const scope = '[data-made-expression="instrument"]';
const stack = tokens.font.$value.map(value => value.includes(' ') ? JSON.stringify(value) : value).join(', ');
const declarations = values => Object.entries(values).map(([name, value]) => `  --md-instrument-${name}: ${value};`).join('\n');
const css = `/* Generated by scripts/build-instrument.mjs. Do not edit. HSL channels support existing Tailwind opacity modifiers. */
${scope} {
  --md-instrument-font: ${stack};
${declarations(tokens.light)}
  --md-instrument-radius: ${tokens.radius};
  --md-instrument-control-height: ${tokens['control-height']};
  --md-instrument-touch-target: ${tokens['touch-target']};
}
.dark ${scope}, ${scope}.dark {
${declarations(tokens.dark)}
}
`;
const outputs = {
  'dist/instrument.css': css,
  'dist/instrument.tokens.json': JSON.stringify(tokens, null, 2) + '\n',
  'dist/instrument.js': `// Generated from src/instrument.tokens.json.\nexport const instrumentTokens = ${JSON.stringify(tokens, null, 2)};\n`,
  'dist/instrument.d.ts': 'export declare const instrumentTokens: { font: { $type: string; $value: string[] }; light: Record<string, string>; dark: Record<string, string>; radius: string; "control-height": string; "touch-target": string; $description: string };\n',
};
mkdirSync(new URL('dist/', root), { recursive: true });
for (const [name, content] of Object.entries(outputs)) {
  const target = new URL(name, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== content) throw new Error(`Stale artifact: ${name}`);
  } else writeFileSync(target, content);
}
console.log(`Instrument artifacts ${process.argv.includes('--check') ? 'verified' : 'generated'} in ${fileURLToPath(root)}`);
